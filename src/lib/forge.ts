// Parsers for what `trustabl forge` writes (SKILL.md) and what
// `trustabl forge check` prints. Formats are those of trustabl 0.1.14.

export interface ForgeStamp {
  raw: string
  generated: string
  rules: string
  schema: string
  sdks: string[]
  template: string
}

// <!-- generated: 2026-10-19 | rules: f57df3f… | schema: 23 | sdks: openai_sdk | template: 3 -->
const STAMP_RE = /<!--\s*generated:[^>]*-->/

export function parseStamp(skill: string): ForgeStamp | null {
  const m = skill.match(STAMP_RE)
  if (!m) return null
  const raw = m[0]
  const body = raw.replace(/^<!--\s*/, '').replace(/\s*-->$/, '')
  const fields: Record<string, string> = {}
  for (const part of body.split('|')) {
    const i = part.indexOf(':')
    if (i === -1) continue
    fields[part.slice(0, i).trim()] = part.slice(i + 1).trim()
  }
  if (!fields.generated || !fields.rules) return null
  return {
    raw,
    generated: fields.generated,
    rules: fields.rules,
    schema: fields.schema ?? '',
    sdks: (fields.sdks ?? '').split(',').map((s) => s.trim()).filter(Boolean),
    template: fields.template ?? '',
  }
}

export type OtelInSkill = 'encoded' | 'partial' | 'none'

export interface SkillOutline {
  hasApplyLoop: boolean
  tracingLanguages: string[]
  otel: OtelInSkill
  sections: { title: string; scopes: { scope: string; rules: string[] }[] }[]
}

/**
 * What the skill instructs, read from its own headings:
 *  - "## How to Apply These Constraints" — the apply loop
 *  - "## Runtime Tracing" with "#### <Language>" blocks; "Step 2 — Add the
 *    Trustabl labels (agent-reliability-otel-labels)" is the enriched-OTel part
 *  - one "## <SDK>" section per detected SDK with "### Tool Rules" … and
 *    "#### [RULE-ID] title" per rule
 * OTel "encoded" = the tracing section includes the labels step; "partial" =
 * tracing without labels; "none" = no tracing section.
 */
export function outlineSkill(skill: string): SkillOutline {
  const lines = skill.split(/\r?\n/)
  const outline: SkillOutline = { hasApplyLoop: false, tracingLanguages: [], otel: 'none', sections: [] }
  let h2 = ''
  let hasTracing = false
  let hasLabels = false
  let section: SkillOutline['sections'][number] | null = null
  let scope: { scope: string; rules: string[] } | null = null
  for (const line of lines) {
    const h = line.match(/^(#{2,5})\s+(.*)$/)
    if (!h) continue
    const level = h[1].length
    const text = h[2].trim()
    if (level === 2) {
      h2 = text
      section = null
      scope = null
      if (/^How to Apply These Constraints/i.test(text)) outline.hasApplyLoop = true
      else if (/^Runtime Tracing/i.test(text)) hasTracing = true
      else {
        section = { title: text, scopes: [] }
        outline.sections.push(section)
      }
      continue
    }
    if (/^Runtime Tracing/i.test(h2)) {
      if (level === 3 && /agent-reliability-otel-labels/i.test(text)) hasLabels = true
      if (level === 4 && /^(Python|TypeScript|Go)$/i.test(text) && !outline.tracingLanguages.includes(text)) {
        outline.tracingLanguages.push(text)
      }
      continue
    }
    if (section && level === 3 && /Rules$/i.test(text)) {
      scope = { scope: text.replace(/\s*Rules$/i, ''), rules: [] }
      section.scopes.push(scope)
      continue
    }
    if (scope && level === 4) {
      const r = text.match(/^\[([A-Z0-9-]+)\]/)
      if (r) scope.rules.push(r[1])
    }
  }
  outline.otel = hasTracing ? (hasLabels ? 'encoded' : 'partial') : 'none'
  return outline
}

export type ForgeCheckStatus = 'pass' | 'stale' | 'unstamped' | 'missing' | 'error'

export interface ForgeCheckResult {
  status: ForgeCheckStatus
  /** Human cause, as the CLI said it. */
  detail: string
  cause?: 'rules' | 'template' | 'rules+template'
  stampRules?: string
  currentRules?: string
  stampTemplate?: string
  currentTemplate?: string
}

/** Interpret `trustabl forge check <file>`: exit 0 current, 1 stale /
 *  unstamped / not found, 2 environment error. */
export function parseForgeCheck(exitCode: number | null, stdout: string, stderr: string): ForgeCheckResult {
  const text = `${stdout}\n${stderr}`.trim()
  const firstLine = text.split(/\r?\n/).find((l) => l.trim()) ?? ''
  if (exitCode === 0) {
    const m = text.match(/up to date \(rules: ([0-9a-f]+)/i)
    return { status: 'pass', detail: firstLine, currentRules: m?.[1], stampRules: m?.[1] }
  }
  if (exitCode === 1) {
    if (/file not found/i.test(text)) return { status: 'missing', detail: firstLine }
    if (/no forge stamp found/i.test(text)) return { status: 'unstamped', detail: firstLine }
    // Three shapes (trustabl 0.1.14):
    //   outdated: generated from A, current rules are B
    //   outdated: generated by an older forge (template 2, current 3) — rules are current
    //   outdated: rules A→B and template 2→3
    const both = text.match(/rules ([0-9a-f]+)\s*→\s*([0-9a-f]+) and template (\S+?)\s*→\s*(\S+)/i)
    const rules = both ? [both[0], both[1], both[2]] : text.match(/generated from ([0-9a-f]+), current rules are ([0-9a-f]+)/i)
    const tmpl = both ? [both[0], both[3], both[4]] : text.match(/older forge \(template (\S+), current (\S+)\)/i)
    const res: ForgeCheckResult = { status: 'stale', detail: firstLine }
    if (rules) { res.stampRules = rules[1]; res.currentRules = rules[2] }
    if (tmpl) { res.stampTemplate = tmpl[1]; res.currentTemplate = tmpl[2].replace(/[),]+$/, '') }
    res.cause = rules && tmpl ? 'rules+template' : tmpl ? 'template' : 'rules'
    return res
  }
  return { status: 'error', detail: firstLine || `forge check exited with code ${exitCode}` }
}

/** "trustabl forge: no SDKs detected … accepted categories: [a b c]" → the categories. */
export function parseNoSdk(stderr: string): { noSdk: boolean; categories: string[] } {
  if (!/no SDKs detected/i.test(stderr)) return { noSdk: false, categories: [] }
  const m = stderr.match(/accepted categories:\s*\[([^\]]*)\]/i)
  return { noSdk: true, categories: m ? m[1].split(/\s+/).filter(Boolean) : [] }
}

/** Short explanation of why a skill is stale, from the check result. */
export function staleReason(c: ForgeCheckResult): string {
  if (c.status === 'unstamped') return 'SKILL.md has no forge stamp, so it cannot be checked. Regenerate it.'
  if (c.status === 'missing') return 'No SKILL.md on disk.'
  if (c.status !== 'stale') return ''
  const parts: string[] = []
  if (c.cause?.includes('rules')) parts.push(`stamp rules ${c.stampRules ?? '?'} ≠ current ${c.currentRules ?? '?'}`)
  if (c.cause?.includes('template')) parts.push(`template ${c.stampTemplate ?? '?'} ≠ current ${c.currentTemplate ?? '?'}`)
  return `Skill stamp is stale: ${parts.join('; ')}.`
}
